-- 레인체크(rain check): 비로 라운드를 다 못 친 손님에게 **사람마다** 한 장씩 주는 크레딧 전표.
--
-- 흐름
--   1) 티 시트에서 결제한(paid) 플레이어 카드의 Rain check 를 누른다. 금액과 만료일을 확인하고
--      발행하면 서버가 코드(`RC-` + 무작위 10자)를 매기고, 화면이 그 코드를 Code 128 바코드로 담은
--      전표를 사람마다 한 장씩 찍는다(손님용 + 보관용).
--   2) 다음에 오면 계산서 결제에서 수단 "Rain check" 를 고르고 전표 바코드를 쏜다. 서버가 코드를
--      잠그고 상태(발행됨)·만료일·금액을 확인한 뒤, 결제와 **같은 트랜잭션**에서 사용됨으로 바꾼다.
--
-- 규칙
-- - 한 사람(예약의 플레이어 하나)에게 살아 있는 레인체크는 하나뿐이다. 다시 찍을 때는 같은 코드로
--   재인쇄한다(REPRINT 표시). 잘못 발행했으면 사유를 적고 무효(void)로 한 뒤 다시 발행한다.
-- - 금액(센트, 세금 포함)의 기본값은 **그 사람이 실제로 낸 돈**이다. 계산서로 받은 그린피는 그 줄에서
--   읽는다(줄 할인 뒤 + 계산서 할인 몫을 빼고 + 세금 몫). GolfNow 선결제·컴프처럼 $0 으로 닫힌
--   사람에게 정가 크레딧이 나가면 안 되기 때문이다. 계산서 이전 방식(티 시트 토글)으로 낸 사람만
--   예약의 그린피 + 카트 + HST 로 계산한다. 직원은 금액을 낮출 수 있지만 낸 돈보다 높일 수는 없다.
--   몇 홀을 쳤을 때 얼마를 돌려주는지는 클럽 정책이라 여기서 정하지 않는다.
-- - 만료일의 기본값은 발행일 + 1년(`pelham_rc_default_expiry`). 발행 창에서 바꿀 수 있다.
--   만료 판정은 매장 현지 날짜(토론토)로 한다 — 만료일 당일까지 쓸 수 있다.
-- - 크레딧은 한 번에 쓴다. 계산서가 크레딧보다 작으면 남는 몫은 사라진다(화면이 미리 경고한다).
-- - 레인체크를 발행한 계산서를 환불하면: 아직 안 쓴 레인체크는 무효가 되고, 이미 쓴 것이 있으면
--   환불을 거절한다(돈을 두 번 돌려주게 된다). 레인체크로 결제한 계산서를 환불하면 그 레인체크는
--   다시 쓸 수 있는 상태로 돌아간다.
-- - 살아 있는 레인체크가 있는 플레이어는 티 시트에서 "Mark unpaid"·삭제할 수 없다.
--
-- 회계: 레인체크로 받은 돈은 결제 수단 `rain_check` 로 따로 잡힌다(현금 시재에 들어가지 않는다).
--
-- 공유 프로젝트 규칙(0005 와 같다): 전부 `pelham_` 접두사, 테이블은 RLS 를 켜고 정책 없음,
-- 직원 함수는 첫 줄이 `pelham_require_staff()`. 오류는 PT404/PT409/PT422.
--
-- 전제: 0005(계산서). 0006–0010 과는 독립이다.
-- 실행: SQL editor 에 이 파일 전체를 붙여 한 번. 다시 실행해도 안전하다.

-- ===== 먼저 확인 ======================================================
do $$
declare
  v_missing text[] := '{}';
  v_name text;
begin
  foreach v_name in array array['pelham_fail', 'pelham_iso', 'pelham_require_staff', 'pelham_tee_audit',
                                 'pelham_tee_save', 'pelham_tee_lock', 'pelham_pos_today', 'pelham_pos_tax',
                                 'pelham_pos_find_player', 'pelham_pos_tee_price', 'pelham_pos_lock_open',
                                 'pelham_pos_recalc', 'pelham_pos_move', 'pelham_staff_bill_pay'] loop
    if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                    where n.nspname = 'public' and p.proname = v_name) then
      v_missing := v_missing || (v_name || '()');
    end if;
  end loop;
  if to_regclass('public.pelham_bill_payments') is null then
    v_missing := v_missing || 'pelham_bill_payments'::text;
  end if;
  if cardinality(v_missing) > 0 then
    raise exception '0011 needs 0005 first. Missing: %', array_to_string(v_missing, ', ');
  end if;
end;
$$;

-- ===== 테이블 ==========================================================

create table if not exists public.pelham_rain_checks (
  id                bigint generated by default as identity primary key,
  -- 전표의 바코드 값. 무작위다 — 순번이면 옆 번호를 쳐서 남의 크레딧을 쓸 수 있다.
  code              text not null unique check (code ~ '^RC-[0-9A-F]{10}$'),
  status            text not null default 'issued' check (status in ('issued', 'redeemed', 'void')),
  -- 누구의 어느 라운드인가. 이름·날짜는 발행 시점 값을 복사한다(예약이 바뀌어도 전표는 그대로).
  booking_id        text not null,
  player_id         text not null,
  player_name       text not null,
  tee_date          date,
  tee_time          text,
  holes             integer,
  -- 직원이 적은 친 홀 수. 전표에 찍히는 참고값이고 금액을 정하지 않는다.
  holes_played      integer check (holes_played is null or holes_played between 0 and 18),
  -- 크레딧(센트, 세금 포함)과 그 사람이 낸 돈(발행 당시 계산값, 상한).
  amount            integer not null check (amount > 0),
  paid_value        integer not null check (paid_value >= 0),
  -- 그린피를 받은 계산서. 티 시트 토글로 받았으면 null.
  source_bill_id    bigint references public.pelham_bills (id),
  issued_on         date not null,
  expires_on        date not null,
  cashier           text,
  note              text,
  issued_by         uuid,
  issued_at         timestamptz not null default now(),
  redeemed_bill_id  bigint references public.pelham_bills (id),
  redeemed_at       timestamptz,
  void_reason       text,
  voided_at         timestamptz,
  check (expires_on >= issued_on),
  check ((status = 'redeemed') = (redeemed_bill_id is not null)),
  check ((status = 'void') = (voided_at is not null))
);
-- 한 사람에게 살아 있는(발행·사용) 레인체크는 하나.
create unique index if not exists pelham_rain_checks_player_once
  on public.pelham_rain_checks (booking_id, player_id) where status in ('issued', 'redeemed');
create index if not exists pelham_rain_checks_booking_idx on public.pelham_rain_checks (booking_id);
create index if not exists pelham_rain_checks_source_idx on public.pelham_rain_checks (source_bill_id);
create index if not exists pelham_rain_checks_redeemed_idx on public.pelham_rain_checks (redeemed_bill_id);

alter table public.pelham_rain_checks enable row level security;
revoke all on public.pelham_rain_checks from anon, authenticated;

-- 결제 줄: 수단에 rain_check 를 더하고, 어느 레인체크인지 적는다.
alter table public.pelham_bill_payments
  add column if not exists rain_check_id bigint references public.pelham_rain_checks (id);

