      check ((method = 'rain_check') = (rain_check_id is not null));
  end if;
end;
$$;

-- ===== 헬퍼 (실행 권한을 아무에게도 주지 않는다) ========================

-- 기본 만료일: 발행일 + 1년. 클럽 정책이 정해지면 여기 한 곳만 바꾼다.
create or replace function public.pelham_rc_default_expiry(p_issued date)
returns date
language sql
immutable
set search_path = ''
as $$
  select (p_issued + interval '1 year')::date
$$;

create or replace function public.pelham_rc_json(r public.pelham_rain_checks)
returns jsonb
language sql
stable
set search_path = ''
as $$
  select jsonb_build_object(
    'id', r.id,
    'code', r.code,
    'status', r.status,
    -- 화면이 "만료됨"을 따로 보여 준다. 상태를 바꾸지는 않는다(만료는 날짜로만 판정).
    'expired', r.status = 'issued' and r.expires_on < public.pelham_pos_today(),
    'booking_id', r.booking_id,
    'player_id', r.player_id,
    'player_name', r.player_name,
    'tee_date', to_char(r.tee_date, 'YYYY-MM-DD'),
    'tee_time', r.tee_time,
    'holes', r.holes,
    'holes_played', r.holes_played,
    'amount', r.amount,
    'paid_value', r.paid_value,
    'source_receipt', (select b.receipt_no from public.pelham_bills b where b.id = r.source_bill_id),
    'issued_on', to_char(r.issued_on, 'YYYY-MM-DD'),
    'expires_on', to_char(r.expires_on, 'YYYY-MM-DD'),
    'cashier', r.cashier,
    'note', r.note,
    'issued_at', public.pelham_iso(r.issued_at),
    'redeemed_receipt', (select b.receipt_no from public.pelham_bills b where b.id = r.redeemed_bill_id),
    'redeemed_at', public.pelham_iso(r.redeemed_at),
    'void_reason', r.void_reason,
    'voided_at', public.pelham_iso(r.voided_at)
  )
$$;

-- 한 플레이어가 낸 돈(센트, 세금 포함)과 그 계산서. 레인체크 금액의 기본값이자 상한.
-- 계산서로 받았으면 그 줄: 줄 합계(줄 할인 뒤) − 계산서 할인의 이 줄 몫 + 세금의 이 줄 몫.
-- 몫은 줄 합계 비율로 나눈다. 계산서 이전 방식이면 예약의 그린피 + 카트 + HST.
create or replace function public.pelham_rc_paid_value(p_booking text, p_doc jsonb, p_player jsonb,
                                                       out paid_value integer, out bill_id bigint)
language plpgsql
stable
set search_path = ''
as $$
declare
  l record;
  v_net integer;
  v_taxable integer;
begin
  select li.line_total, b.id, b.subtotal, b.discount, b.tax into l
    from public.pelham_bill_lines li join public.pelham_bills b on b.id = li.bill_id
   where li.booking_id = p_booking and li.player_id = p_player->>'id'
     and li.kind = 'tee_player' and li.active and b.status = 'paid'
   order by b.paid_at desc
   limit 1;
  if l.id is not null then
    bill_id := l.id;
    v_net := l.line_total;
    if l.subtotal > 0 and l.discount > 0 then
      v_net := v_net - round(l.discount::numeric * l.line_total / l.subtotal)::integer;
    end if;
    v_net := greatest(v_net, 0);
    v_taxable := l.subtotal - l.discount;
    paid_value := v_net + case when v_taxable > 0
                               then round(l.tax::numeric * v_net / v_taxable)::integer else 0 end;
  else
    bill_id := null;
    v_net := public.pelham_pos_tee_price(p_doc, p_player);
    paid_value := v_net + public.pelham_pos_tax(v_net);
  end if;
end;
$$;

-- ===== 직원 함수 ======================================================

-- 발행 전 확인: 이 사람이 낸 돈(기본 금액), 기본 만료일, 이미 있는 레인체크.
create or replace function public.pelham_staff_rain_check_quote(p_booking text, p_player text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_doc jsonb;
  v_player jsonb;
  v_paid integer;
  v_bill bigint;
  v_today date := public.pelham_pos_today();
  r public.pelham_rain_checks;
begin
  perform public.pelham_require_staff();
  select t.doc into v_doc from public.pelham_tee_bookings t where t.id = p_booking;
  if v_doc is null then
    perform public.pelham_fail('404', 'Booking not found');
  end if;
  v_player := public.pelham_pos_find_player(v_doc, p_player);
  if v_player is null then
    perform public.pelham_fail('404', 'Player not found on this reservation');
  end if;
  select * into r from public.pelham_rain_checks
   where booking_id = p_booking and player_id = p_player and status in ('issued', 'redeemed');
  select q.paid_value, q.bill_id into v_paid, v_bill from public.pelham_rc_paid_value(p_booking, v_doc, v_player) q;
  return jsonb_build_object(
    'player_name', coalesce(nullif(btrim(v_player->>'name'), ''), 'Guest'),
    'paid', coalesce((v_player->>'paid')::boolean, false),
    'paid_value', v_paid,
    'source_receipt', (select b.receipt_no from public.pelham_bills b where b.id = v_bill),
    'issued_on', to_char(v_today, 'YYYY-MM-DD'),
    'default_expires_on', to_char(public.pelham_rc_default_expiry(v_today), 'YYYY-MM-DD'),
    'existing', case when r.id is null then null else public.pelham_rc_json(r) end
  );
end;
$$;

-- 발행. p: {booking_id, player_id, amount?, expires_on?, holes_played?, cashier?, note?}
create or replace function public.pelham_staff_rain_check_issue(p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_doc jsonb;
  v_player jsonb;
  v_booking text := p->>'booking_id';
  v_player_id text := p->>'player_id';
  v_paid integer;
  v_bill bigint;
  v_amount integer;
  v_today date := public.pelham_pos_today();
  v_expires date;
  v_holes_played integer;
  v_code text;
  v_name text;
  r public.pelham_rain_checks;
begin
  perform public.pelham_require_staff();
  p := coalesce(p, '{}'::jsonb);
  if v_booking is null or v_player_id is null then
    perform public.pelham_fail('422', 'booking_id and player_id are required.');
  end if;

  select t.doc into v_doc from public.pelham_tee_bookings t where t.id = v_booking;
  if v_doc is null then
    perform public.pelham_fail('404', 'Booking not found');
  end if;
  -- 티 시트 쓰기와 같은 잠금 순서(슬롯 → 예약 행). 결제·환불과 엇갈리지 않게.
  perform public.pelham_tee_lock((v_doc->>'date')::date, v_doc->>'time');
  select t.doc into v_doc from public.pelham_tee_bookings t where t.id = v_booking for update;

  v_player := public.pelham_pos_find_player(v_doc, v_player_id);
  if v_player is null then
    perform public.pelham_fail('404', 'Player not found on this reservation');
  end if;
  v_name := coalesce(nullif(btrim(v_player->>'name'), ''), 'Guest');
  if coalesce((v_player->>'cancelled')::boolean, false) then
    perform public.pelham_fail('409', format('%s is cancelled.', v_name));
  end if;
  if not coalesce((v_player->>'paid')::boolean, false) then
    perform public.pelham_fail('409', format('%s has not paid. A rain check is credit for a paid round.', v_name));
  end if;
  select code into v_code from public.pelham_rain_checks
   where booking_id = v_booking and player_id = v_player_id and status in ('issued', 'redeemed');
  if v_code is not null then
    perform public.pelham_fail('409', format('%s already has rain check %s. Reprint it, or void it first.', v_name, v_code));
  end if;

  select q.paid_value, q.bill_id into v_paid, v_bill from public.pelham_rc_paid_value(v_booking, v_doc, v_player) q;
  begin
    v_amount := coalesce((p->>'amount')::integer, v_paid);
    v_expires := coalesce(nullif(p->>'expires_on', '')::date, public.pelham_rc_default_expiry(v_today));
    v_holes_played := nullif(p->>'holes_played', '')::integer;
  exception when others then
    perform public.pelham_fail('422', 'amount (cents), expires_on (YYYY-MM-DD) or holes_played is not valid.');
  end;
  if v_amount <= 0 then
    perform public.pelham_fail('422', format('%s paid nothing for this round, so there is no credit to give.', v_name));
  end if;
  if v_amount > v_paid then
    perform public.pelham_fail('422', format('A rain check cannot be more than %s paid (%s cents).', v_name, v_paid));
  end if;
  if v_expires < v_today then
    perform public.pelham_fail('422', 'The expiry date is in the past.');
  end if;
  if v_expires > (v_today + interval '3 years')::date then
    perform public.pelham_fail('422', 'The expiry date is more than three years away.');
  end if;
  if v_holes_played is not null and v_holes_played not between 0 and 18 then
    perform public.pelham_fail('422', 'Holes played must be between 0 and 18.');
  end if;

  -- 코드: 무작위 10자(16진). 겹치면 다시 뽑는다.
  loop
    v_code := 'RC-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));
    exit when not exists (select 1 from public.pelham_rain_checks where code = v_code);
  end loop;

  insert into public.pelham_rain_checks
    (code, booking_id, player_id, player_name, tee_date, tee_time, holes, holes_played,
     amount, paid_value, source_bill_id, issued_on, expires_on, cashier, note, issued_by)
  values
    (v_code, v_booking, v_player_id, v_name, (v_doc->>'date')::date, v_doc->>'time',
     nullif(v_doc->>'holes', '')::integer, v_holes_played, v_amount, v_paid, v_bill, v_today, v_expires,
     nullif(btrim(coalesce(p->>'cashier', '')), ''), nullif(btrim(coalesce(p->>'note', '')), ''), auth.uid())
  returning * into r;

  v_doc := public.pelham_tee_audit(v_doc,
             format('Rain check %s issued to %s: %s, valid through %s.', v_code, v_name,
                    '$' || to_char(v_amount / 100.0, 'FM999,990.00'), to_char(v_expires, 'YYYY-MM-DD')),
             public.pelham_iso(now()));
  perform public.pelham_tee_save(v_doc);

  return public.pelham_rc_json(r);
end;
$$;

-- 한 예약의 레인체크 전부(무효 포함, 발행 순). 플레이어 카드가 상태를 보여 준다.
create or replace function public.pelham_staff_rain_checks(p_booking text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  perform public.pelham_require_staff();
  return coalesce((
    select jsonb_agg(public.pelham_rc_json(r) order by r.issued_at, r.id)
      from public.pelham_rain_checks r where r.booking_id = p_booking
  ), '[]'::jsonb);
end;
$$;

-- 코드로 찾기(결제 칸에서 전표를 쐈을 때). 쓸 수 있는지는 화면이 status·expired 로 보여 주고,
-- 실제 판정은 결제 함수가 잠금 안에서 다시 한다.
create or replace function public.pelham_staff_rain_check(p_code text)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  r public.pelham_rain_checks;
begin
  perform public.pelham_require_staff();
  select * into r from public.pelham_rain_checks where code = upper(btrim(coalesce(p_code, '')));
  if r.id is null then
    perform public.pelham_fail('404', format('No rain check %s', coalesce(p_code, '')));
  end if;
  return public.pelham_rc_json(r);
end;
$$;

-- 무효. 아직 안 쓴 것만. 사유는 필수 — 크레딧을 없애는 일이다.
create or replace function public.pelham_staff_rain_check_void(p_code text, p_reason text)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  r public.pelham_rain_checks;
begin
  perform public.pelham_require_staff();
  if length(btrim(coalesce(p_reason, ''))) = 0 then
    perform public.pelham_fail('422', 'Give a reason for voiding the rain check.');
  end if;
  select * into r from public.pelham_rain_checks where code = upper(btrim(coalesce(p_code, ''))) for update;
  if r.id is null then
    perform public.pelham_fail('404', format('No rain check %s', coalesce(p_code, '')));
  end if;
  if r.status <> 'issued' then
    perform public.pelham_fail('409', format('Rain check %s is already %s.', r.code, r.status));
  end if;
  update public.pelham_rain_checks
     set status = 'void', voided_at = now(), void_reason = btrim(p_reason)
   where id = r.id
  returning * into r;
  return public.pelham_rc_json(r);
end;
$$;

