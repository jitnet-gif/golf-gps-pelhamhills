"""Cart paths and the clubhouse from OpenStreetMap -> frontend/src/data/cartPaths.ts.

    python scripts/build-cart-paths.py                 # ask Overpass
    python scripts/build-cart-paths.py saved.json      # use an Overpass answer saved earlier

What it keeps: every way tagged golf=cartpath, and highway=service (the drive
from Webber Road to the car park), inside the course's box. Nothing is joined or
invented here - lib/cartRoute.ts decides at run time what counts as a junction
and draws the gaps between pieces as straight, dashed legs.

As of 2026-09-16 OSM has 44 such ways in 20 disconnected pieces, and none
around holes 13-15. Cart paths an admin drives with the recorder in /admin/map
(table cart_paths, migration 0011) are laid over these on every phone.

The clubhouse is OSM way 662700441: the largest building beside the car park,
north of the 1st and 10th tees. It is not tagged as a clubhouse in OSM, so the
choice is ours.

Data (c) OpenStreetMap contributors, ODbL.
"""

from __future__ import annotations

import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

BOX = (42.976, -79.310, 42.992, -79.292)  # south, west, north, east
CLUBHOUSE_WAY = 662700441
OUT = Path(__file__).resolve().parents[1] / "frontend" / "src" / "data" / "cartPaths.ts"
MIRRORS = (
    "https://overpass-api.de/api/interpreter",
    "https://maps.mail.ru/osm/tools/overpass/api/interpreter",
    "https://overpass.kumi.systems/api/interpreter",
)


def fetch() -> dict:
    s, w, n, e = BOX
    box = f"({s},{w},{n},{e})"
    query = (
        "[out:json][timeout:90];("
        f'way["golf"="cartpath"]{box};'
        f'way["highway"="service"]{box};'
        f"way({CLUBHOUSE_WAY});"
        ");out body geom;"
    )
    body = urllib.parse.urlencode({"data": query}).encode()
    last: Exception | None = None
    for url in MIRRORS:
        try:
            request = urllib.request.Request(url, data=body, headers={"User-Agent": "golf-gps-app/1.0"})
            with urllib.request.urlopen(request, timeout=150) as response:
                return json.load(response)
        except Exception as exc:  # a busy mirror is normal; try the next
            last = exc
    raise SystemExit(f"Overpass did not answer: {last}")


def main() -> None:
    data = json.load(open(sys.argv[1], encoding="utf-8")) if len(sys.argv) > 1 else fetch()
    lines: list[tuple[int, list[list[float]]]] = []
    clubhouse: tuple[float, float] | None = None
    for element in data["elements"]:
        tags = element.get("tags", {})
        geometry = element.get("geometry") or []
        if element["id"] == CLUBHOUSE_WAY and geometry:
            ring = geometry[:-1] if geometry[0] == geometry[-1] else geometry
            clubhouse = (
                round(sum(p["lat"] for p in ring) / len(ring), 7),
                round(sum(p["lon"] for p in ring) / len(ring), 7),
            )
        elif tags.get("golf") == "cartpath" or tags.get("highway") == "service":
            points = [[round(p["lat"], 7), round(p["lon"], 7)] for p in geometry]
            if len(points) >= 2:
                lines.append((element["id"], points))
    if clubhouse is None:
        raise SystemExit(f"way {CLUBHOUSE_WAY} (the clubhouse) was not in the answer")
    lines.sort()

    out = [
        "// Generated by scripts/build-cart-paths.py - do not edit by hand.",
        "// Cart paths and the clubhouse: (c) OpenStreetMap contributors, ODbL.",
        "import type { FairwayPoint } from './pelhamHills';",
        "",
        "export interface CartPathLine {",
        "  /** 'osm-<way id>' here; the row id for a path recorded in /admin/map. */",
        "  id: string;",
        "  points: FairwayPoint[];",
        "}",
        "",
        f"/** {len(lines)} OSM ways. Not joined: see lib/cartRoute.ts. */",
        "export const OSM_CART_PATHS: CartPathLine[] = [",
    ]
    for way_id, points in lines:
        coords = ", ".join(f"[{lat}, {lng}]" for lat, lng in points)
        out.append(f"  {{ id: 'osm-{way_id}', points: [{coords}] }},")
    out += [
        "];",
        "",
        f"/** Middle of OSM way {CLUBHOUSE_WAY}, the building beside the car park. */",
        f"export const CLUBHOUSE: FairwayPoint = [{clubhouse[0]}, {clubhouse[1]}];",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{len(lines)} paths, clubhouse {clubhouse} -> {OUT}")


if __name__ == "__main__":
    main()
