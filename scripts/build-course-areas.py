"""The course's drawn areas from OpenStreetMap -> frontend/src/data/courseAreas.ts.

    python scripts/build-course-areas.py                 # ask Overpass
    python scripts/build-course-areas.py saved.json      # use an Overpass answer saved earlier

What it keeps, inside the course outline (OSM way 56217508): the outline itself,
woods, the driving range, fairways, tees, greens, bunkers and water as areas,
and streams as lines. Hole lines, tees and pins are not taken - the app has its
own (data/pelhamHills.ts). The Full map's 'OSM 지도' style lays these over the
satellite map the way the OSM editor shows them.

As of 2026-10-25 OSM has 18 greens, 18 fairways, 18 tees, 12 bunkers, 9 water
areas and 13 woods here.

Data (c) OpenStreetMap contributors, ODbL.
"""

from __future__ import annotations

import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

COURSE_WAY = 56217508
OUT = Path(__file__).resolve().parents[1] / "frontend" / "src" / "data" / "courseAreas.ts"
MIRRORS = (
    "https://overpass-api.de/api/interpreter",
    "https://maps.mail.ru/osm/tools/overpass/api/interpreter",
    "https://overpass.kumi.systems/api/interpreter",
)
# Drawn bottom first: a green sits on its fairway, a fairway on the woods.
ORDER = ("course", "wood", "driving_range", "fairway", "tee", "green", "bunker", "water")


def fetch() -> dict:
    query = (
        "[out:json][timeout:90];"
        f"way({COURSE_WAY});map_to_area->.c;("
        'way(area.c)["golf"~"^(fairway|tee|green|bunker|driving_range|water_hazard|lateral_water_hazard)$"];'
        'way(area.c)["natural"~"^(water|wood)$"];'
        'way(area.c)["landuse"="forest"];'
        'way(area.c)["waterway"~"^(stream|ditch|drain)$"];'
        f"way({COURSE_WAY});"
        ");out body geom;"
    )
    body = urllib.parse.urlencode({"data": query}).encode()
    last: Exception | None = None
    for url in MIRRORS:
        try:
            request = urllib.request.Request(url, data=body, headers={"User-Agent": "golf-gps-app/1.0"})
            with urllib.request.urlopen(request, timeout=150) as response:
                return json.load(response)
        except Exception as exc:  # a busy mirror is normal; try the next
            last = exc
    raise SystemExit(f"Overpass did not answer: {last}")


def kind_of(element: dict) -> str | None:
    tags = element.get("tags", {})
    golf = tags.get("golf")
    if element["id"] == COURSE_WAY:
        return "course"
    if golf in ("fairway", "tee", "green", "bunker", "driving_range"):
        return golf
    if golf in ("water_hazard", "lateral_water_hazard") or tags.get("natural") == "water":
        return "water"
    if tags.get("natural") == "wood" or tags.get("landuse") == "forest":
        return "wood"
    if tags.get("waterway") in ("stream", "ditch", "drain"):
        return "stream"
    return None


def main() -> None:
    data = json.load(open(sys.argv[1], encoding="utf-8")) if len(sys.argv) > 1 else fetch()
    areas: list[tuple[int, int, str, list[list[float]]]] = []
    streams: list[tuple[int, list[list[float]]]] = []
    for element in data["elements"]:
        kind = kind_of(element)
        geometry = element.get("geometry") or []
        # 6 places is about 10 cm - finer than the imagery under it.
        points = [[round(p["lat"], 6), round(p["lon"], 6)] for p in geometry]
        if kind == "stream" and len(points) >= 2:
            streams.append((element["id"], points))
        elif kind is not None and len(points) >= 4 and points[0] == points[-1]:
            areas.append((ORDER.index(kind), element["id"], kind, points[:-1]))
    if not any(kind == "course" for _, _, kind, _ in areas):
        raise SystemExit(f"way {COURSE_WAY} (the course outline) was not in the answer")
    areas.sort()
    streams.sort()

    def coords(points: list[list[float]]) -> str:
        return ", ".join(f"[{lat}, {lng}]" for lat, lng in points)

    out = [
        "// Generated by scripts/build-course-areas.py - do not edit by hand.",
        "// Course areas: (c) OpenStreetMap contributors, ODbL.",
        "import type { FairwayPoint } from './pelhamHills';",
        "",
        "export type CourseAreaKind = " + " | ".join(f"'{k}'" for k in ORDER) + ";",
        "",
        "export interface CourseArea {",
        "  /** 'osm-<way id>'. */",
        "  id: string;",
        "  kind: CourseAreaKind;",
        "  /** The outline, not closed: the last point does not repeat the first. */",
        "  points: FairwayPoint[];",
        "}",
        "",
        f"/** {len(areas)} OSM areas, bottom first: draw them in this order. */",
        "export const OSM_COURSE_AREAS: CourseArea[] = [",
    ]
    for _, way_id, kind, points in areas:
        out.append(f"  {{ id: 'osm-{way_id}', kind: '{kind}', points: [{coords(points)}] }},")
    out += [
        "];",
        "",
        f"/** {len(streams)} OSM streams and ditches, as lines. */",
        "export const OSM_STREAMS: { id: string; points: FairwayPoint[] }[] = [",
    ]
    for way_id, points in streams:
        out.append(f"  {{ id: 'osm-{way_id}', points: [{coords(points)}] }},")
    out += ["];", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    counts = {k: sum(1 for _, _, kind, _ in areas if kind == k) for k in ORDER}
    print(f"{counts}, {len(streams)} streams -> {OUT}")


if __name__ == "__main__":
    main()
