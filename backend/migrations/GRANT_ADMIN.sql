-- 이미 관리자였거나, 그 이메일로 가입한 계정이 없거나. 2번 목록의 '이미_관리자'
-- 칸으로 구별됩니다.
--
-- 그 사람이 앱에서 로그아웃 후 다시 로그인하면 /admin 운영 화면이 열립니다.


-- ----------------------------------------------------------------------------
-- 2. 계정 목록  (이 파일을 그냥 Run 하면 이것이 나옵니다 - 읽기만 합니다)
-- ----------------------------------------------------------------------------
-- francis 로 보이는 계정이 맨 위로 올라옵니다. 목록에 없으면 그 사람은 아직
-- 앱에서 회원가입을 하지 않은 것입니다 - /login 에서 가입부터 하게 하세요.
SELECT u.email AS 계정,
       to_char(u.created_at AT TIME ZONE 'America/Toronto', 'MM-DD HH24:MI') AS 가입,
       EXISTS (SELECT 1 FROM public.scorecard_admins a WHERE a.user_id = u.id) AS 이미_관리자,
       CASE WHEN u.email ILIKE '%francis%' THEN '<-- francis 로 보이는 계정' ELSE '' END AS 표시
  FROM auth.users u
 ORDER BY (u.email ILIKE '%francis%') DESC, u.created_at DESC
 LIMIT 30;


