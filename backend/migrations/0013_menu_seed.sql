-- 겹치는지 알려 주고 멈춥니다 - 어느 줄을 지울지는 사람이 정할 일입니다.
BEGIN
  CREATE UNIQUE INDEX IF NOT EXISTS idx_menu_items_name ON public.menu_items (lower(name));
EXCEPTION WHEN unique_violation THEN
  RAISE EXCEPTION
    '메뉴에 이름이 같은 줄이 이미 있습니다. 아래로 찾아서 하나만 남기고 지운 뒤 다시 실행하세요: %',
    'SELECT lower(name), count(*) FROM public.menu_items GROUP BY 1 HAVING count(*) > 1;';
END;

